/**
 * Icons that admins can pick for landing page rows, matching Setting::LANDING_ICONS.
 */
export default function LandingIcon({
    name,
    size = 20,
    className,
}: {
    name: string;
    size?: number;
    className?: string;
}) {
    if (name === 'telegram') {
        return <TelegramIcon size={size} />;
    }

    if (name === 'whatsapp') {
        return <WhatsAppIcon size={size} />;
    }

    const filledPath =
        name === 'messenger'
            ? MESSENGER_PATH
            : name in STROKE_ICONS
              ? null
              : (SOCIAL_ICON_PATHS[name] ?? null);

    if (filledPath) {
        return (
            <svg
                width={size}
                height={size}
                viewBox="0 0 24 24"
                fill="currentColor"
                className={className}
                aria-hidden
            >
                <path d={filledPath} />
            </svg>
        );
    }

    return (
        <svg
            width={size}
            height={size}
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            strokeWidth={2}
            strokeLinecap="round"
            strokeLinejoin="round"
            className={className}
            aria-hidden
        >
            {STROKE_ICONS[name] ?? STROKE_ICONS.globe}
        </svg>
    );
}
